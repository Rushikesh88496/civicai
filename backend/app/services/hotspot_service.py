"""Predictive Hotspots service layer (Part 23, Part 36).

Facades the ML pipeline behind async, DB-bound operations:

* ``train_hotspots`` — loads REAL complaint records (user GPS or explicit manual
  map selection) from the database, builds the discrete-time training corpus and
  runs the time-aware training loop (CPU-bound, offloaded to a thread), writes
  the joblib artifact and records it in the ``predictive_models`` registry
  (exactly one active).
* ``get_status`` — exposes the active model + its evaluation metrics.
* ``get_predictions`` — live inference: real complaints (last 30 days) feed the
  same feature extractor the model was trained on; risk = P(>=1 complaint in
  the next ``horizon`` days) per grid cell, plus expected volume. Hotspot
  coordinates are the crowd centroids of the real complaint coordinates in each
  cell — never predefined, random or demo positions.

Hard guarantees (Part 36):

* Training data comes EXCLUSIVELY from complaint records stored in the database;
  complaint coordinates come from GPS or an explicitly user-selected map point.
* With zero complaints the surfaces report ``INSUFFICIENT_DATA`` (or "no model
  trained yet") and return zero cells — simply opening the hotspot page never
  creates a prediction.
* A model is only served when its bundle was trained on real complaints
  (``config.training_source == "real_complaints"``); legacy synthetic-trained
  artifacts are refused.
"""

