def _asset_out(asset: InfrastructureAsset) -> InfrastructureAssetOut:
    ward = asset.ward
    return InfrastructureAssetOut(
        id=str(asset.id),
        name=asset.name,
        category=asset.category.value if hasattr(asset.category, "value") else str(asset.category),
        ward_id=str(asset.ward_id) if asset.ward_id else None,
        ward_code=ward.code if ward else None,
        ward_name=ward.name if ward else None,
        latitude=asset.latitude,
        longitude=asset.longitude,
        address=asset.address,
        installed_at=asset.installed_at,
        condition_note=asset.condition_note,
        is_active=asset.is_active,
        created_at=asset.created_at,
    )


async def list_assets(db: AsyncSession) -> list[InfrastructureAssetOut]:
    rows = (
        await db.execute(
            select(InfrastructureAsset)
            .options(selectinload(InfrastructureAsset.ward))
            .where(InfrastructureAsset.is_active.is_(True))
            .order_by(InfrastructureAsset.created_at.asc())
        )
    ).scalars().all()
    return [_asset_out(a) for a in rows]


async def register_asset(
    db: AsyncSession, payload: InfrastructureAssetIn
) -> InfrastructureAssetOut:
    if payload.category not in InfrastructureCategory.__members__:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=f"Unknown infrastructure category: {payload.category}",
)
    asset = InfrastructureAsset(
        name=payload.name,
        category=InfrastructureCategory(payload.category),
        ward_id=uuid.UUID(payload.ward_id) if payload.ward_id else None,
        latitude=payload.latitude,
        longitude=payload.longitude,
        address=payload.address,
        installed_at=payload.installed_at,
        condition_note=payload.condition_note,
        is_active=True,
    )
    db.add(asset)
    await db.commit()
    await db.refresh(asset)
    # Resolve the ward eagerly so the response schema never lazy-loads.
    if asset.ward_id:
        asset.ward = await db.get(Ward, asset.ward_id)
    return _asset_out(asset)


