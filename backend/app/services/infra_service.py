# Live inference
# --------------------------------------------------------------------------- #
def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371.0088
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def _count_near(
    lat: float | None,
    lon: float | None,
    points: list[tuple[float, float]],
    radius_km: float,
) -> int:
    if lat is None or lon is None:
        return 0
    return sum(1 for plat, plon in points if _haversine_km(lat, lon, plat, plon) <= radius_km)


async def _live_history(
    db: AsyncSession,
    assets: list[InfrastructureAsset],
    settings: Settings,
) -> tuple[dict[uuid.UUID, dict], dict[uuid.UUID, float]]:
    """Per-asset {complaints_90d, repairs_12m} + ward resident counts."""
    now = datetime.now(UTC)
    radius_km = settings.INFRA_RADIUS_M / 1000.0

    complaint_points: list[tuple[float, float]] = []
    complaints_since = now - timedelta(days=settings.INFRA_COMPLAINTS_LOOKBACK_DAYS)
    complaint_rows = (
        await db.execute(
            select(ComplaintLocation.latitude, ComplaintLocation.longitude)
            .join(Complaint, Complaint.id == ComplaintLocation.complaint_id)
            .where(
                Complaint.created_at >= complaints_since,
                ComplaintLocation.latitude.is_not(None),
                ComplaintLocation.longitude.is_not(None),
            )
        )
    ).all()
    complaint_points = [(float(r[0]), float(r[1])) for r in complaint_rows]

    repair_points: list[tuple[float, float]] = []
    repairs_since = now - timedelta(days=settings.INFRA_REPAIRS_LOOKBACK_DAYS)
    repair_rows = (
        await db.execute(
            select(ComplaintLocation.latitude, ComplaintLocation.longitude)
            .join(Complaint, Complaint.id == ComplaintLocation.complaint_id)
            .join(WorkOrder, WorkOrder.complaint_id == Complaint.id)
            .where(
                WorkOrder.created_at >= repairs_since,
                ComplaintLocation.latitude.is_not(None),
                ComplaintLocation.longitude.is_not(None),
            )
        )
).all()
    repair_points = [(float(r[0]), float(r[1])) for r in repair_rows]

    counts: dict[uuid.UUID, dict] = {}
    for asset in assets:
        counts[asset.id] = {
            "complaints_90d": _count_near(
                asset.latitude, asset.longitude, complaint_points, radius_km
            ),
            "repairs_12m": _count_near(
                asset.latitude, asset.longitude, repair_points, radius_km
            ),
        }

    residents: dict[uuid.UUID, float] = {}
    res_rows = (
        await db.execute(
            select(Ward.id, func.count(User.id).label("residents"))
            .join(User, User.ward_id == Ward.id)
            .group_by(Ward.id)
        )
    ).all()
    residents = {str(wid): float(c) for wid, c in res_rows}
    return counts, residents


async def get_predictions(
    db: AsyncSession,
    user: User,
    settings: Settings | None = None,
) -> InfrastructurePredictions:
    settings = settings or get_settings()

    # Part 31 gate: forecasts require a real registered fleet. No lazy
    # provisioning — an empty asset registry must STAY empty of AI output.
    registered = await _asset_count(db)
    if registered < settings.INFRA_MIN_ASSETS:
        return InfrastructurePredictions(
            ai_prediction=True,
            disclaimer=_DISCLAIMER,
            prediction_status=PredictionStatus.INSUFFICIENT_DATA,
            model=None,
            assets=[],
            message=_infra_gate_message(registered, settings.INFRA_MIN_ASSETS),
            registered_assets=registered,
            minimum_assets=settings.INFRA_MIN_ASSETS,
        )

    row = await db.scalar(
        select(InfrastructureModel).where(InfrastructureModel.is_active.is_(True))
    )
    if row is None:
        await train(db, user, settings)
        row = await db.scalar(
            select(InfrastructureModel).where(InfrastructureModel.is_active.is_(True))
        )
        if row is None:
            raise RuntimeError("Infrastructure training failed to produce an active model")

    bundle = await asyncio.to_thread(
        load_bundle, str(_artifact_path(settings, row.artifact_filename))
    )

    assets = (
        (
            await db.execute(
                select(InfrastructureAsset)
                .options(selectinload(InfrastructureAsset.ward))
                .where(InfrastructureAsset.is_active.is_(True))
                .order_by(InfrastructureAsset.name.asc())
            )
        )
        .scalars()
        .all()
    )

    counts, residents = await _live_history(db, assets, settings)
    rain_mm, rain_available = await fetch_infra_citywide_rainfall(settings)

    reference = datetime.now(UTC)
    feature_rows: list[dict] = []
    for asset in assets:
        installed = asset.installed_at
        history = counts.get(asset.id, {"complaints_90d": 0, "repairs_12m": 0})
        age = age_years(installed, reference)
        feature_rows.append(
            build_feature_dict(
                category=asset.category.value,
                age=age,
                complaints_90d=history["complaints_90d"],
                repairs_12m=history["repairs_12m"],
                rainfall_mm=rain_mm if rain_available else None,
                residents=residents.get(str(asset.ward_id)) if asset.ward_id else None,
                location_available=asset.latitude is not None and asset.longitude is not None,
            )
        )

    proba: list[float] = []
    if feature_rows:
        live_frame = pd.DataFrame(feature_rows, columns=feature_columns())
        predicted = await asyncio.to_thread(predict_from_bundle, bundle, live_frame)
        proba = [float(p) for p in predicted]

    predictions: list[AssetPrediction] = []
    for i, asset in enumerate(assets):
        prob = proba[i] if i < len(proba) else 0.0
        risk = risk_level_for_probability(prob, settings)
        recommended = recommendation_for(risk, asset.category.value)
        history = counts.get(asset.id, {"complaints_90d": 0, "repairs_12m": 0})
        age = age_years(asset.installed_at, reference)
        ward_label = None
        if asset.ward:
            ward_label = f"{asset.ward.code} ({asset.ward.name})"
        factors = supporting_factors_for(
            category=asset.category.value,
            age=age,
            age_available=asset.installed_at is not None,
            complaints_90d=history["complaints_90d"],
            repairs_12m=history["repairs_12m"],
            rainfall_mm=rain_mm if rain_available else None,
            ward_label=ward_label,
            location_available=asset.latitude is not None and asset.longitude is not None,
        )
        history_snapshot = {
            "complaints_90d": history["complaints_90d"],
            "repairs_12m": history["repairs_12m"],
            "age_years": round(age, 2),
            "radius_m": settings.INFRA_RADIUS_M,
            "rainfall_available": rain_available,
            "lookback_days": settings.INFRA_COMPLAINTS_LOOKBACK_DAYS,
        }

        stored = InfrastructurePrediction(
            asset_id=asset.id,
            model_version=row.version,
            failure_probability=round(prob, 4),
            risk_level=risk,
            recommended_inspection=recommended,
            supporting_factors=factors,
            history=history_snapshot,
            ai_prediction=True,
            review_status=PredictionReviewStatus.PENDING,
        )
        db.add(stored)
        await db.flush()
        predictions.append(
            AssetPrediction(
                id=str(stored.id),
                asset=_asset_out(asset),
                model_version=row.version,
                failure_probability=round(prob, 4),
                risk_level=risk.value,
                recommended_inspection=recommended,
                supporting_factors=factors,
                history=history_snapshot,
                ai_prediction=True,
                review_status=stored.review_status.value,
                predicted_at=stored.created_at,
            )
        )

    await db.commit()

    predictions.sort(key=lambda p: p.failure_probability, reverse=True)
    return InfrastructurePredictions(
        ai_prediction=True,
        disclaimer=_DISCLAIMER,
        prediction_status=PredictionStatus.READY,
        inference_at=reference,
        model=_model_info(row),
        assets=predictions,
        assets_assessed=len(predictions),
        assets_skipped=0,
        horizon_days=bundle["config"]["horizon_days"],
        message="Forecasts served from the trained infrastructure model.",
        registered_assets=registered,
        minimum_assets=settings.INFRA_MIN_ASSETS,
    )


