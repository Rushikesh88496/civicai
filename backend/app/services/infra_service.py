"""Predictive Infrastructure Maintenance service layer (Part 24).

Facades the infra ML pipeline behind async, DB-bound operations:

* ``train`` - builds the deterministic synthetic asset corpus, runs the
  time-aware training loop (offloaded to a thread), writes the joblib artifact
  and records it in the ``infrastructure_models`` registry (exactly one active).
* ``get_status`` - exposes the active infra model + its evaluation metrics.
* ``list_assets`` / ``register_asset`` - asset registry management.
* ``get_predictions`` - live inference: real asset records, nearby complaints,
  repair history, ward population and (optionally) rainfall feed the same
  feature extractor the model was trained on; risk = P(failure within the
  horizon). Every output is flagged ``ai_prediction`` and phrased as predicted
  risk / recommended inspection.
* ``review_prediction`` / ``create_preventive_work_order`` - the officer review
  workflow and the optional preventive work order raised on an approved asset.
"""

