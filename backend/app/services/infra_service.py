_DISCLAIMER = (
    "AI-predicted maintenance risk for infrastructure assets, generated by the "
    "trained infrastructure model. This is a forecast, NOT a confirmed list of "
    "failing assets. Probabilities blend historical complaints, repair history, "
    "asset age, weather and location signals and may be wrong; verify any "
    "at-risk asset before dispatching."
)

_EXPECTED_REVIEW_DECISIONS = {
    PredictionReviewStatus.APPROVED.value,
    PredictionReviewStatus.REJECTED.value,
}


def _artifact_path(settings: Settings, filename: str) -> Path:
    return Path(settings.INFRA_ARTIFACT_DIR) / filename


# --------------------------------------------------------------------------- #
# Training / status
# --------------------------------------------------------------------------- #
async def _train_sync(settings: Settings) -> dict:
    return await asyncio.to_thread(run_infra_training, settings)


async def _next_version(db: AsyncSession) -> int:
    last = await db.scalar(select(func.max(InfrastructureModel.version)))
    return int(last) + 1 if last else 1


def _model_info(row: InfrastructureModel) -> InfrastructureModelInfo:
    return InfrastructureModelInfo(
        version=row.version,
        kind=row.kind,
        status=row.status,
        is_active=row.is_active,
        trained_at=row.trained_at,
        artifact_filename=row.artifact_filename,
        metrics=row.metrics or {},
        config=row.config or {},
    )


async def _asset_count(db: AsyncSession) -> int:
    return int(
        await db.scalar(
            select(func.count(InfrastructureAsset.id)).where(InfrastructureAsset.is_active.is_(True))
        )
        or 0
    )


async def get_status(
    db: AsyncSession,
    settings: Settings | None = None,
) -> InfrastructureStatus:
    settings = settings or get_settings()
    registered = await _asset_count(db)
    row = await db.scalar(
        select(InfrastructureModel).where(InfrastructureModel.is_active.is_(True))
    )
    if row is None:
        return InfrastructureStatus(
            trained=False,
            prediction_status=PredictionStatus.INSUFFICIENT_DATA,
            model=None,
            message=_infra_gate_message(registered, settings.INFRA_MIN_ASSETS),
            registered_assets=registered,
            minimum_assets=settings.INFRA_MIN_ASSETS,
        )
    if registered < settings.INFRA_MIN_ASSETS:
        return InfrastructureStatus(
            trained=True,
            prediction_status=PredictionStatus.INSUFFICIENT_DATA,
            model=_model_info(row),
            message=_infra_gate_message(registered, settings.INFRA_MIN_ASSETS),
            registered_assets=registered,
            minimum_assets=settings.INFRA_MIN_ASSETS,
        )
    return InfrastructureStatus(
        trained=True,
        prediction_status=PredictionStatus.READY,
        model=_model_info(row),
        message="Active predictive infrastructure model, forecasts are being served.",
        registered_assets=registered,
        minimum_assets=settings.INFRA_MIN_ASSETS,
    )


def _infra_gate_message(registered: int, minimum: int) -> str:
    return (
        "The infrastructure model is not ready yet: "
        f"{registered}/{minimum} registered assets are required. Register real "
        "assets in the asset registry before forecasts are enabled."
    )


async def train(
    db: AsyncSession,
    user: User | None,
    settings: Settings | None = None,
) -> InfrastructureTrainingOut:
    settings = settings or get_settings()

    # Part 31 gate: refuse to train without a real, on-the-books fleet.
    registered = await _asset_count(db)
    if registered < settings.INFRA_MIN_ASSETS:
        return InfrastructureTrainingOut(
            trained=False,
            status=PredictionStatus.INSUFFICIENT_DATA,
            message=_infra_gate_message(registered, settings.INFRA_MIN_ASSETS),
            registered_assets=registered,
            minimum_assets=settings.INFRA_MIN_ASSETS,
        )

    started = time.monotonic()
    bundle = await _train_sync(settings)
    duration = round(time.monotonic() - started, 2)

    version = await _next_version(db)
    filename = f"infrastructure_v{version}.joblib"
    path = _artifact_path(settings, filename)
    path.parent.mkdir(parents=True, exist_ok=True)
    await asyncio.to_thread(save_bundle, bundle, str(path))

    await db.execute(
        update(InfrastructureModel)
        .where(InfrastructureModel.is_active.is_(True))
        .values(is_active=False)
    )
    row = InfrastructureModel(
        version=version,
        kind=bundle["kind"],
        artifact_filename=filename,
        metrics=bundle["metrics"],
        config=bundle["config"],
        status="ready",
        is_active=True,
        trained_by_user_id=user.id if user else None,
        trained_at=datetime.now(UTC),
    )
    db.add(row)
    await db.commit()
    await db.refresh(row)

    return InfrastructureTrainingOut(
        trained=True,
        status=PredictionStatus.READY,
        version=version,
        model=_model_info(row),
        metrics=bundle["metrics"],
        config=bundle["config"],
        rows=bundle["config"]["training_rows"],
        duration_seconds=duration,
        message="Infrastructure model trained on the configured asset corpus.",
        registered_assets=registered,
        minimum_assets=settings.INFRA_MIN_ASSETS,
    )


